-- metadata/apply_tags.sql
-- Apply tags to tables and columns (fully qualified, no USE statements)

USE ROLE DATA_OWNER;

-- Don't set database context - use fully qualified names for everything

-- ============================================
-- TAG RAW.PUBLIC TABLES
-- ============================================

