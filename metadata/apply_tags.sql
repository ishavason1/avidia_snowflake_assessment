-- ============================================
-- TAG SENSITIVE/CDE COLUMNS
--
-- CLASSIFICATION is intentionally not set here. It is assigned only by
-- classification/10_sync_confirmed_classification_tags.sql after a steward
-- approves a review decision.
-- ============================================

