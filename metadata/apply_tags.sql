  SET TAG GOVERNANCE.CATALOG.LAYER = 'RAW',
      GOVERNANCE.CATALOG.DOMAIN = 'CUSTOMER',
      GOVERNANCE.CATALOG.SOURCE_SYSTEM = 'DATA_GENERATOR',
      GOVERNANCE.CATALOG.CERTIFICATION = 'IN_PROGRESS',
      GOVERNANCE.CATALOG.DATA_OWNER = 'Banking Operations';

